function countryPassesFilter(name, mode) {
  if (mode === 'all') { return true; }
  var iso3 = nameToIso3[name];
  var hasFigure = iso3 ? fraSoc.hasValue(iso3) : false;
  if (mode === 'gap') {
    // The gap-filling audience: files FRA reports (has a forest-area row) but
    // no soil carbon value in any year. Territories outside FRA entirely are
    // not gaps -- there is no report to fill.
    return !hasFigure && !!fraStats.FRA_FOREST_AREA[name];
  }
  if (!hasFigure) { return false; }
  if (mode === 'any') { return true; }
  return fraSoc.isDeskStudy(iso3) === (mode === 'desk');
}

function rebuildCountryItems(mode) {
  var names = gaulLut.country_names.filter(function (n) {
    return countryPassesFilter(n, mode);
  });
  var current = countrySelect.getValue();
  countrySelect.items().reset([GLOBAL_OPTION].concat(names));
  var keep = (current === GLOBAL_OPTION) || (names.indexOf(current) !== -1);
  if (keep) {
    countrySelect.setValue(current, false);
  } else {
    // Fire the change: display, preview and results-clear all follow the one
    // onChange path, avoiding the Select's set-after-reset display race.
    countrySelect.setValue(GLOBAL_OPTION, true);
  }
}

