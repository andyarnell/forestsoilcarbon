// Native scale per asset, read once (a blocking getInfo) and cached for the
// session, so previews stay instant after the first native-scale lookup.
var nativeScaleCache = {};

function nativeScaleOf(assetId, band) {
  if (!(assetId in nativeScaleCache)) {
    var s = null;
    try {
      var img = ee.Image(assetId);
      img = band ? img.select([band]) : img.select([0]);
      s = img.projection().nominalScale().getInfo();
    } catch (e) {
      s = null;  // bad custom asset ID -- caller falls back
    }
    // The WGS84 default projection reports ~111 km: the asset carries no real
    // grid of its own (composites do this), so 'native' is meaningless.
    if (s !== null && s > 10000) { s = null; }
    nativeScaleCache[assetId] = s;
  }
  return nativeScaleCache[assetId];
}

/**
 * The analysis scale in metres for the current dropdown choice. 'native' is
 * the soil carbon layer's own grid -- carbon is the layer that must not be
 * resampled; forest fractions replicate to any grid without error.
 * @param {Object} socCfg
 * @return {number}
 */
function resolveAnalysisScale(socCfg) {
  var choice = scaleSelect.getValue();
  if (choice !== NATIVE_SCALE_KEY) { return Number(choice); }
  return nativeScaleOf(socCfg.asset, socCfg.band) || DEFAULT_SCALE;
}

/**
 * Resolve the current widget selections into configs, regions and images.
 * Pure read: no drawing, no server computation. Null when a custom config is
 * incomplete.
 * @return {Object|null}
 */
function buildRunContext() {
  var socCfg = resolveSocConfig();
  var forestCfg = resolveForestConfig();
  if (!socCfg || !forestCfg) { return null; }

  var countryName = countrySelect.getValue();
  if (!countryName) { return null; }  // transient during list rebuilds
  var scale = resolveAnalysisScale(socCfg);
  var isGlobal = (countryName === GLOBAL_OPTION);
  var regions = getRegions(countryName);

  var socImage = buildSocImage(socCfg);
  var forestArea = buildForestArea(forestCfg);
  var forestFraction = buildForestFraction(forestCfg);

  // Clip what is drawn to the selected country. The statistics are restricted
  // by reduceRegions over the same polygons, so clipping changes no number --
  // but it stops the map showing a global layer while the panel reports one
  // country, and it makes a click outside the border read "no data".
  function clipToCountry(img) {
    return isGlobal ? img : img.clip(regions);
  }

  return {
    socCfg: socCfg, forestCfg: forestCfg,
    countryName: countryName, scale: scale, isGlobal: isGlobal, regions: regions,
    socImage: socImage, forestArea: forestArea,
    socDisplay: clipToCountry(socImage),
    forestFractionDisplay: clipToCountry(forestFraction),
    forestAreaDisplay: clipToCountry(forestArea)
  };
}

/**
 * Draw a context's layers, replacing whatever is on the map.
 * @param {Object} ctx  from buildRunContext
 */
function drawLayers(ctx) {
  map.layers().reset();
  markerLayer = null;

  map.addLayer(ctx.socDisplay,
               ctx.socCfg.quantity === 'stock' ? SOC_STOCK_VIS : SOC_CONC_VIS,
               'Soil carbon (' + QUANTITY[ctx.socCfg.quantity].unit + ')', true, 0.8);
  map.addLayer(ctx.forestFractionDisplay.selfMask(), FOREST_VIS,
               'Forest: ' + ctx.forestCfg.label, true, 0.7);

  // The per-pixel product is only tonnes of carbon when the input is a stock.
  // For a concentration it is g/kg*ha, which is not a quantity -- do not draw
  // it and do not name it.
  if (QUANTITY[ctx.socCfg.quantity].summable) {
    map.addLayer(ctx.socDisplay.multiply(ctx.forestAreaDisplay).selfMask(),
                 SOC_IN_FOREST_VIS, 'Soil carbon in forest (t C per pixel)', false, 1);
  }

  // Outline the border so the clip is visibly a boundary, not a data gap.
  if (!ctx.isGlobal) {
    map.addLayer(
      ee.Image().byte().paint({featureCollection: ctx.regions, color: 1, width: 2}),
      {palette: ['#222222']}, 'Country boundary', true);
  }
}

/**
 * Redraw map and inspector for the current selection without computing
 * statistics. Tiles render lazily, so this costs no server computation.
 * Called from every layer-affecting widget: the map always shows what is
 * selected. Results are cleared separately -- figures for an abandoned
 * selection are worse than no figures.
 */
function updatePreview() {
  currentCtx = buildRunContext();
  inspectorPanel.clear();
  inspectorPanel.add(ui.Label('Click the map to read pixel values.', HINT_STYLE));
  if (!currentCtx) {
    map.layers().reset();
    markerLayer = null;
    return;
  }
  drawLayers(currentCtx);
}

function clearResultsForNewSelection() {
  if (!uiReady) { return; }
  resultsPanel.clear();
  // Red: this replaces figures the user may have been reading, and the map
  // now shows a selection those figures never described.
  resultsPanel.add(ui.Label('Selection changed - press Run analysis.', WARN_STYLE));
  markRunStale();
}

function runAnalysis() {
  resultsPanel.clear();

  var ctx = buildRunContext();
  if (!ctx) {
    showMessage('Enter the custom asset ID first.', WARN_STYLE);
    return;
  }
  currentCtx = ctx;
  drawLayers(ctx);
  inspectorPanel.clear();
  inspectorPanel.add(ui.Label('Click the map to read pixel values.', HINT_STYLE));

  var socCfg = ctx.socCfg;
  var forestCfg = ctx.forestCfg;
  var countryName = ctx.countryName;
  var scale = ctx.scale;
  var quantity = QUANTITY[socCfg.quantity];
  var socImage = ctx.socImage;
  var forestArea = ctx.forestArea;
  var regions = ctx.regions;

  showMessage(countryName, KICKER_STYLE);

  if (socCfg.quantity === 'unknown') {
    showMessage('Cannot compute.', HEADING_STYLE);
    showMessage('You have not told the app what the values in this layer mean. A stock ' +
                '(tonnes of carbon per hectare) and a concentration (grams of carbon ' +
                'per kilogram of soil) are different physical quantities, and the app ' +
                'cannot tell them apart from the pixel values.', WARN_STYLE);
    showMessage('The layer is on the map so you can inspect it. Over forest, a 0-30 cm ' +
                'stock usually reads about 30-150 t C/ha and a concentration about ' +
                '5-60 g/kg - but check the asset description rather than guessing.', HINT_STYLE);
    showMessage('Set "What the values mean" under Soil carbon layer, then Run again.');
    return;
  }

  // Only now is the selection actually being computed -- the unknown-quantity
  // return above leaves the '*' in place because nothing ran.
  clearRunStale();
  showMessage('Computing...', HINT_STYLE);

  // Statistics run on the UNCLIPPED images -- reduceRegions already restricts
  // to `regions`, so clipping first would just add work.
  var stats = computeCountryStats(socImage, forestArea, regions, scale, socCfg);

  computeTotals(stats, socCfg).evaluate(function (result, error) {
    resultsPanel.clear();
    showMessage(countryName, KICKER_STYLE);

    if (error) { showMessage('Failed: ' + error, WARN_STYLE); return; }
    if (!result || result.mean === null) {
      showMessage('No data returned. Try a coarser analysis scale.', WARN_STYLE);
      return;
    }

    var depthLabel = socCfg.depth_cm.replace('-', '–') + ' cm';
    // Both blocks share the same row labels (Soil carbon / Forest area), so
    // the estimate and the FRA report read as one line-by-line comparison.
    var estHead = 'Estimated from ' + (socCfg.short_label || socCfg.label) + ' · ' +
                  (forestCfg.short_label || forestCfg.label);

    // Below ~1 kha the bold mean would describe next to nothing -- say so on
    // the value itself, and print the area in hectares rather than a rounded
    // "0.0 kha".
    var tinyForest = result.forest_area_ha < 1000;
    var areaLine = tinyForest
        ? 'Forest area: ' + formatNumber(result.forest_area_ha, 0) + ' ha'
        : 'Forest area: ' + formatNumber(result.forest_area_ha / 1000, 1) + ' kha';

    if (quantity.summable) {
      showMessage(estHead, BLOCKHEAD_STYLE);
      showMessage('Soil carbon: ' + formatNumber(result.mean, 1) + ' t C/ha (mean, ' +
                  depthLabel + (tinyForest
                      ? ', over just ' + formatNumber(result.forest_area_ha, 0) +
                        ' ha of forest'
                      : '') + ')', EST_VALUE_STYLE);
      showMessage(areaLine);
      addReportedBlock(socCfg, countryName);
    } else {
      showMessage(estHead, BLOCKHEAD_STYLE);
      showMessage('Soil carbon concentration: ' + formatNumber(result.mean, 1) +
                  ' g/kg (mean, ' + depthLabel + ')', EST_VALUE_STYLE);
      showMessage(areaLine);
      // No reported block here: FRA values are stocks, and echoing them beside
      // a concentration invites exactly the comparison this warning forbids.
      showMessage('NOT the FRA figure. This layer is a concentration - how carbon-rich ' +
                  'the soil is. FRA asks for a stock - how much carbon is there, in ' +
                  'tonnes per hectare. A g/kg value cannot be entered in place of a ' +
                  't C/ha value.', WARN_STYLE);
    }

    // Both expanders start closed on every run.
    appState.ui.qualityCollapsed = true;
    appState.ui.detailsCollapsed = true;

    var q = buildQualityWidgets(socCfg, countryName, result.coverage_pc);
    if (q.widgets.length) {
      resultsPanel.add(makeCollapsible('Soil data quality', q.widgets, 'qualityCollapsed',
                                       q.caution ? AMBER_BTN : null));
    }
    resultsPanel.add(makeCollapsible(
        'Details',
        buildDetailsWidgets(result, socCfg, forestCfg, countryName, scale),
        'detailsCollapsed'));

    addDownloadLink(stats, socCfg, forestCfg, countryName, scale);
  });

  if (!IS_PUBLISHED_APP && driveExportCheckbox.getValue()) {
    Export.table.toDrive({
      collection: stats,
      folder: 'fra_soc_gap_filling',
      description: 'soc_in_forest_' + forestCfg.key + '_' + socCfg.key,
      fileFormat: 'CSV'
    });
    showMessage('Drive export queued - see the Tasks tab.', HINT_STYLE);
  }
}

