// PIXEL INSPECTOR
// The inputs are continuous (soil carbon per hectare, fractional forest cover),
// so the value at a point is worth reading directly -- it is how you tell a
// suspicious country mean from a genuine one, and how you check a national
// asset's units and scale factor before trusting a whole run.
// =============================================================================

function showInspectorMessage(text, style) {
  inspectorPanel.add(ui.Label(text, style || BODY_STYLE));
}

/**
 * Sample every layer of the current selection at a clicked point.
 * @param {Object} coords  {lon, lat} from ui.Map.onClick
 */
function inspectPixel(coords) {
  inspectorPanel.clear();

  if (!currentCtx) {
    showInspectorMessage('Choose layers first - a custom asset needs its ID entered.',
                         HINT_STYLE);
    return;
  }

  var point = ee.Geometry.Point([coords.lon, coords.lat]);

  if (markerLayer) { map.layers().remove(markerLayer); }
  markerLayer = ui.Map.Layer(point, {color: 'red'}, 'Inspected point');
  map.layers().add(markerLayer);

  showInspectorMessage(formatNumber(coords.lat, 4) + ', ' +
                       formatNumber(coords.lon, 4), HEADING_STYLE);
  showInspectorMessage('Reading...', HINT_STYLE);

  var quantity = QUANTITY[currentCtx.socCfg.quantity];

  // One band per reported value, so this costs a single server round trip.
  var stack = currentCtx.socDisplay.rename('soc_value')
    .addBands(currentCtx.forestFractionDisplay.rename('forest_fraction'))
    .addBands(currentCtx.forestAreaDisplay.rename('forest_area_ha'));

  stack.reduceRegion({
    reducer: ee.Reducer.first(),
    geometry: point,
    scale: currentCtx.scale
  }).evaluate(function (values, error) {
    inspectorPanel.clear();
    showInspectorMessage(formatNumber(coords.lat, 4) + ', ' +
                         formatNumber(coords.lon, 4), HEADING_STYLE);

    if (error) {
      showInspectorMessage('Could not read this point: ' + error, WARN_STYLE);
      return;
    }
    if (!values) {
      showInspectorMessage('No data at this point.', HINT_STYLE);
      return;
    }

    // null means masked -- no data here -- which is different from zero and is
    // worth saying, because masked soil pixels are what drag the coverage down.
    var soc = values.soc_value;
    var fraction = values.forest_fraction;
    var areaHa = values.forest_area_ha;

    var isBlank = function (v) { return v === null || v === undefined; };

    // Everything masked with a country selected means the click landed outside
    // the clip, which is a different thing from a genuine data gap inside it.
    if (!currentCtx.isGlobal && isBlank(soc) && isBlank(fraction) && isBlank(areaHa)) {
      showInspectorMessage('Outside ' + currentCtx.countryName + '. The layers are clipped ' +
                           'to the selected country - click inside the border, or switch ' +
                           'to ' + GLOBAL_OPTION + '.', HINT_STYLE);
      return;
    }

    showInspectorMessage('Soil carbon: ' + (soc === null || soc === undefined
      ? 'no data'
      : formatNumber(soc, 1) + ' ' + quantity.unit));

    showInspectorMessage('Forest cover: ' + (fraction === null || fraction === undefined
      ? 'no data'
      : formatNumber(fraction * 100, 1) + '% of pixel'));

    showInspectorMessage('Forest area: ' + (areaHa === null || areaHa === undefined
      ? 'no data'
      : formatNumber(areaHa, 1) + ' ha in pixel'));

    if (quantity.summable && soc !== null && soc !== undefined &&
        areaHa !== null && areaHa !== undefined) {
      showInspectorMessage('Carbon in forest here: ' +
                           formatNumber(soc * areaHa, 1) + ' t C in pixel', HINT_STYLE);
    }

    if ((soc === null || soc === undefined) && areaHa) {
      showInspectorMessage('Forest with no soil carbon data - this pixel is excluded ' +
                           'from the country mean and counts against the coverage %.',
                           WARN_STYLE);
    }

    showInspectorMessage('Sampled at ' + formatNumber(currentCtx.scale, 1) + ' m. Values ' +
                         'are the analysis scale, not the layer\'s native resolution.',
                         HINT_STYLE);
  });
}

/**
 * Upper bound in cm of the app's depth selection, for comparability checks
 * against the depth a country reported to FRA.
 * @param {string} depthCm  a DEPTH_OPTIONS value
 * @return {number|null} null for 'other' -- no comparison possible
 */
function depthUpperCm(depthCm) {
  if (depthCm === '0-30') { return 30; }
  if (depthCm === '0-100') { return 100; }
  return null;
}

/**
 * The "Reported in FRA" block: soil carbon first, aligned with the estimate
 * above it, then forest area. The rows degrade independently -- a country can
 * have an area row and no soil figure, which is exactly the gap-filling
 * audience. Stocks only: FRA has no concentration to echo. Desk-study values
 * are labelled as FAO estimates so the app never validates its own method
 * against itself.
 * @param {Object} socCfg
 * @param {string} countryName
 */
function addReportedBlock(socCfg, countryName) {
  if (countryName === GLOBAL_OPTION) { return; }
  if (!QUANTITY[socCfg.quantity].summable) { return; }

  var iso3 = nameToIso3[countryName] || null;
  var inFra = iso3 ? fraSoc.hasReport(iso3) : false;
  var areaRow = fraStats.FRA_FOREST_AREA[countryName];
  var areaKha = areaRow ? areaRow[FRA_REPORTED.year] : null;

  if (!inFra && (areaKha === null || areaKha === undefined)) {
    showMessage('No FRA report for this territory.', HINT_STYLE);
    return;
  }

  showMessage('Reported in ' + FRA_REPORTED.cycle + ' (' + FRA_REPORTED.year + ' value)',
              BLOCKHEAD_STYLE);

  // Some series stop before the comparison year (Ukraine ends 2010): fall
  // back to the most recent value rather than telling a filtered-in country
  // it has no figure, and say on the row which year it is.
  var soc = iso3 ? fraSoc.getSoc(iso3, FRA_REPORTED.year) : null;
  var socYear = FRA_REPORTED.year;
  if (!soc && iso3) {
    soc = fraSoc.getLatestSoc(iso3);
    if (soc) { socYear = soc.year; }
  }
  if (soc) {
    var suffix;
    if (soc.deskStudy) {
      suffix = 'FAO estimate, not country-reported';
    } else if (soc.depthCm) {
      suffix = 'reported at ' + Math.round(soc.depthCm) + ' cm';
      var upper = depthUpperCm(socCfg.depth_cm);
      if (upper !== null && Math.round(soc.depthCm) !== upper) {
        suffix += ' - not comparable with a ' + socCfg.depth_cm + ' cm estimate';
      }
    } else {
      suffix = 'depth not stated';
    }
    if (String(socYear) !== String(FRA_REPORTED.year)) {
      suffix = socYear + ', latest available - ' + suffix;
    }
    showMessage('Soil carbon: ' + formatNumber(soc.value, 1) + ' t/ha (' + suffix + ')');
    // 2d's second reporting table. Usually one of the pair is entered and the
    // platform derives the other from table 1a forest area -- say which.
    var tot = fraSoc.getSocTotal(iso3, socYear);
    if (tot) {
      showMessage('Total soil carbon: ' + formatNumber(tot.value, 1) + ' Mt (' +
                  (tot.calculated ? 'platform-derived' : 'country-entered') + ')');
    }
  } else {
    showMessage('Soil carbon: no figure in the country report');
  }

  if (areaKha !== null && areaKha !== undefined) {
    showMessage('Forest area: ' + formatNumber(areaKha, 1) + ' kha');
  }
}

/**
 * Content for the "Soil data quality" expander: the dataset's own per-country
 * brief (config key `meta_brief`) plus this run's coverage. caution decides
 * the toggle's amber tint. Generic -- reads only config keys.
 * @param {Object} socCfg
 * @param {string} countryName
 * @param {number|null} coveragePc
 * @return {Object} {widgets: Array, caution: boolean}
 */
function buildQualityWidgets(socCfg, countryName, coveragePc) {
  var widgets = [];
  var brief = (socCfg.meta_brief && countryName !== GLOBAL_OPTION)
      ? socCfg.meta_brief(nameToIso3[countryName] || countryName) : null;
  if (brief) { widgets.push(ui.Label(brief.text, HINT_STYLE)); }
  var hasCoverage = (coveragePc !== null && coveragePc !== undefined);
  if (hasCoverage) {
    widgets.push(ui.Label('Soil data covers ' + formatNumber(coveragePc, 1) +
                          '% of the forest in this run.',
                          coveragePc < LOW_COVERAGE_WARN_PC ? WARN_STYLE : HINT_STYLE));
  }
  var caution = (brief !== null && brief.caution) ||
                (hasCoverage && coveragePc < LOW_COVERAGE_WARN_PC);
  return {widgets: widgets, caution: caution};
}

/**
 * Everything that used to crowd the results panel, behind one expander.
 * @return {Array} widgets for makeCollapsible
 */
function buildDetailsWidgets(result, socCfg, forestCfg, countryName, scale) {
  var w = [];
  if (QUANTITY[socCfg.quantity].summable) {
    w.push(ui.Label('Total soil carbon in forest: ' +
                    formatNumber(result.soc_in_forest_total / 1e6, 1) + ' Mt C.', BODY_STYLE));
    w.push(ui.Label('FRA table 2d takes both the mean (t C/ha, depth in "Soil depth (cm) ' +
                    'used for soil carbon") and a total (million tonnes); the platform ' +
                    'derives whichever is left blank from table 1a forest area.', HINT_STYLE));
  } else {
    w.push(ui.Label('No total is shown: adding up a concentration over an area does not ' +
                    'give a carbon stock. Converting one to the other needs bulk density ' +
                    'and coarse-fragment maps, which this app does not do.', HINT_STYLE));
  }
  w.push(ui.Label('Forest: ' + forestCfg.label, HINT_STYLE));
  w.push(ui.Label('Soil carbon: ' + socCfg.label, HINT_STYLE));
  w.push(ui.Label(socCfg.depth_cm + ' cm ' + socCfg.quantity + ', analysed at ' +
                  formatNumber(scale, 1) + ' m', HINT_STYLE));
  if (socCfg.meta_format && countryName !== GLOBAL_OPTION) {
    var line = socCfg.meta_format(nameToIso3[countryName] || countryName);
    if (line) {
      w.push(ui.Label('Map provenance - ' + line, HINT_STYLE));
    } else if (socCfg.meta_missing) {
      w.push(ui.Label(socCfg.meta_missing, HINT_STYLE));
    }
  }
  w.push(ui.Label(socCfg.citation, HINT_STYLE));
  w.push(ui.Label(forestCfg.citation, HINT_STYLE));
  w.push(ui.Label(fraSoc.CITATION, HINT_STYLE));
  return w;
}

/**
 * Add an in-app CSV download link. Works in a published app, unlike
 * Export.table.toDrive. The mean column name carries its unit, and the total
 * column is omitted entirely when it would not be a meaningful quantity.
 * @param {ee.FeatureCollection} stats
 * @param {Object} socCfg
 * @param {Object} forestCfg
 * @param {string} countryName
 * @param {number} scale
 */
function addDownloadLink(stats, socCfg, forestCfg, countryName, scale) {
  var selectors = ['iso3', 'country', 'forest_area_ha', 'forest_area_with_soc_ha',
                   'soc_data_coverage_pc'];
  if (QUANTITY[socCfg.quantity].summable) {
    selectors.push('soc_in_forest_total');
  }
  selectors.push(meanColumnName(socCfg));
  // Audit-record columns: constants describing the run, on every row, so the
  // CSV alone can justify a figure later.
  selectors = selectors.concat(['soc_dataset', 'forest_dataset', 'depth_cm',
                                'analysis_scale_m', 'boundaries', 'app_version',
                                'run_date']);
  var runDate = new Date().toISOString().slice(0, 10);
  stats = stats.map(function (f) {
    return f.set({
      soc_dataset: socCfg.label,
      forest_dataset: forestCfg.label,
      depth_cm: socCfg.depth_cm,
      analysis_scale_m: scale,
      boundaries: 'GAUL 2024 L0',
      app_version: APP_VERSION,
      run_date: runDate
    });
  });

  var slug = (countryName === GLOBAL_OPTION
    ? 'global'
    : countryName.replace(/[^A-Za-z0-9]+/g, '_'));

  var url = stats.getDownloadURL({
    format: 'csv',
    selectors: selectors,
    filename: 'soc_in_forest_' + slug + '_' + forestCfg.key + '_' + socCfg.key +
              '_' + socCfg.depth_cm + 'cm_' + scale + 'm'
  });

  resultsPanel.add(ui.Label({
    value: '↓ Download record (CSV)',
    style: LINK_STYLE,
    targetUrl: url
  }));
}
